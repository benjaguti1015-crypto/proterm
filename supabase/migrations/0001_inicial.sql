-- ---------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------

create table furgones (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null
);

create table servicios (
  id bigint generated by default as identity primary key,
  nombre text not null unique
);

create table equipos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  categoria text not null check (categoria in ('Muestreo', 'Medición', 'Accesorios')),
  -- Fase 2: todavía no se usan en la aplicación.
  fecha_vencimiento date,
  fecha_calibracion date
);

create table kit_servicio (
  servicio_id bigint not null references servicios (id) on delete cascade,
  equipo_id bigint not null references equipos (id) on delete cascade,
  obligatorio boolean not null default false,
  primary key (servicio_id, equipo_id)
);

create table usuarios (
  id bigint generated by default as identity primary key,
  nombre text not null,
  pin_hash text not null
);

-- El nombre es único sin distinguir mayúsculas: "Pedro" y "pedro" son la misma persona.
create unique index usuarios_nombre_unico on usuarios (lower(nombre));

create table salidas (
  id bigint generated by default as identity primary key,
  furgon_id bigint not null references furgones (id),
  servicio_id bigint not null references servicios (id),
  usuario_id bigint not null references usuarios (id),
  fecha_salida timestamptz not null default now(),
  fecha_retorno_estimada date not null,
  estado text not null default 'abierta' check (estado in ('abierta', 'cerrada')),
  closed_at timestamptz
);

-- Un furgón tiene como máximo una salida abierta.
create unique index salidas_una_abierta_por_furgon on salidas (furgon_id) where estado = 'abierta';

create table salida_items (
  salida_id bigint not null references salidas (id) on delete cascade,
  equipo_id bigint not null references equipos (id),
  devuelto_at timestamptz,
  primary key (salida_id, equipo_id)
);

-- Un equipo no puede estar pendiente de devolución en dos salidas a la vez.
-- Es el último seguro contra la doble reserva.
create unique index salida_items_equipo_en_uso on salida_items (equipo_id) where devuelto_at is null;

-- ---------------------------------------------------------------
-- Vistas
-- ---------------------------------------------------------------

-- Estado de cada equipo. Está "en uso" si tiene un ítem sin devolver
-- en una salida abierta.
create view equipos_estado with (security_invoker = true) as
select
  e.id,
  e.codigo,
  e.nombre,
  e.categoria,
  (u.salida_id is not null) as en_uso,
  u.salida_id,
  u.furgon_id,
  u.furgon_nombre,
  u.responsable,
  u.fecha_retorno_estimada
from equipos e
left join (
  select
    si.equipo_id,
    s.id as salida_id,
    f.id as furgon_id,
    f.nombre as furgon_nombre,
    us.nombre as responsable,
    s.fecha_retorno_estimada
  from salida_items si
  join salidas s on s.id = si.salida_id and s.estado = 'abierta'
  join furgones f on f.id = s.furgon_id
  join usuarios us on us.id = s.usuario_id
  where si.devuelto_at is null
) u on u.equipo_id = e.id;

-- Salidas con los nombres de furgón, servicio y responsable ya resueltos.
create view salidas_detalle with (security_invoker = true) as
select
  s.id,
  s.furgon_id,
  f.nombre as furgon_nombre,
  s.servicio_id,
  sv.nombre as servicio_nombre,
  s.usuario_id,
  us.nombre as responsable,
  s.fecha_salida,
  s.fecha_retorno_estimada,
  s.estado,
  s.closed_at
from salidas s
join furgones f on f.id = s.furgon_id
join servicios sv on sv.id = s.servicio_id
join usuarios us on us.id = s.usuario_id;

-- ---------------------------------------------------------------
-- Funciones
-- ---------------------------------------------------------------

-- Crea una salida y sus ítems en una sola transacción.
-- Revalida que ningún equipo haya sido reservado mientras tanto:
-- si hay conflicto devuelve cuáles son y no guarda nada.
create function crear_salida(
  p_furgon_id bigint,
  p_servicio_id bigint,
  p_usuario_id bigint,
  p_fecha_retorno date,
  p_equipo_ids bigint[]
) returns jsonb
language plpgsql
as $$
declare
  v_ids bigint[];
  v_conflictos jsonb;
  v_salida_id bigint;
begin
  select array_agg(distinct x) into v_ids from unnest(p_equipo_ids) as x;

  if v_ids is null then
    return jsonb_build_object('ok', false, 'error', 'sin_equipos');
  end if;

  -- Bloquea los equipos pedidos: dos confirmaciones simultáneas sobre
  -- el mismo equipo se atienden una después de la otra.
  perform 1 from equipos where id = any (v_ids) order by id for update;

  if exists (
    select 1 from unnest(v_ids) as x
    where not exists (
      select 1 from kit_servicio k where k.servicio_id = p_servicio_id and k.equipo_id = x
    )
  ) then
    return jsonb_build_object('ok', false, 'error', 'fuera_de_kit');
  end if;

  if exists (select 1 from salidas where furgon_id = p_furgon_id and estado = 'abierta') then
    return jsonb_build_object('ok', false, 'error', 'furgon_ocupado');
  end if;

  select jsonb_agg(
    jsonb_build_object(
      'codigo', ee.codigo,
      'nombre', ee.nombre,
      'furgon_nombre', ee.furgon_nombre,
      'responsable', ee.responsable,
      'fecha_retorno_estimada', ee.fecha_retorno_estimada
    ) order by ee.codigo
  )
  into v_conflictos
  from equipos_estado ee
  where ee.id = any (v_ids) and ee.en_uso;

  if v_conflictos is not null then
    return jsonb_build_object('ok', false, 'error', 'conflicto', 'conflictos', v_conflictos);
  end if;

  insert into salidas (furgon_id, servicio_id, usuario_id, fecha_retorno_estimada)
  values (p_furgon_id, p_servicio_id, p_usuario_id, p_fecha_retorno)
  returning id into v_salida_id;

  insert into salida_items (salida_id, equipo_id)
  select v_salida_id, x from unnest(v_ids) as x;

  return jsonb_build_object('ok', true, 'salida_id', v_salida_id);
exception
  -- Dos confirmaciones simultáneas para el mismo furgón.
  when unique_violation then
    return jsonb_build_object('ok', false, 'error', 'furgon_ocupado');
end;
$$;

-- Marca equipos como devueltos. Si no queda ninguno pendiente, cierra la salida.
create function devolver_equipos(
  p_salida_id bigint,
  p_equipo_ids bigint[]
) returns jsonb
language plpgsql
as $$
declare
  v_pendientes integer;
begin
  perform 1 from salidas where id = p_salida_id and estado = 'abierta' for update;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'salida_no_abierta');
  end if;

  update salida_items
  set devuelto_at = now()
  where salida_id = p_salida_id
    and equipo_id = any (p_equipo_ids)
    and devuelto_at is null;

  select count(*) into v_pendientes
  from salida_items
  where salida_id = p_salida_id and devuelto_at is null;

  if v_pendientes = 0 then
    update salidas set estado = 'cerrada', closed_at = now() where id = p_salida_id;
  end if;

  return jsonb_build_object('ok', true, 'cerrada', v_pendientes = 0, 'pendientes', v_pendientes);
end;
$$;

-- ---------------------------------------------------------------
-- Seguridad
-- ---------------------------------------------------------------
-- RLS activado y sin políticas: las claves públicas (anon) no pueden leer
-- ni escribir nada. La aplicación entra solo desde el servidor con la
-- service role key, que no pasa por RLS.

alter table furgones enable row level security;
alter table servicios enable row level security;
alter table equipos enable row level security;
alter table kit_servicio enable row level security;
alter table usuarios enable row level security;
alter table salidas enable row level security;
alter table salida_items enable row level security;

revoke all on furgones, servicios, equipos, kit_servicio, usuarios, salidas, salida_items,
  equipos_estado, salidas_detalle
  from anon, authenticated;

grant all on furgones, servicios, equipos, kit_servicio, usuarios, salidas, salida_items,
  equipos_estado, salidas_detalle
  to service_role;

revoke execute on function crear_salida(bigint, bigint, bigint, date, bigint[]) from public, anon, authenticated;
revoke execute on function devolver_equipos(bigint, bigint[]) from public, anon, authenticated;
grant execute on function crear_salida(bigint, bigint, bigint, date, bigint[]) to service_role;
grant execute on function devolver_equipos(bigint, bigint[]) to service_role;
